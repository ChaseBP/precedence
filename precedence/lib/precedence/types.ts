// ───────────────────────────── Lifecycle ─────────────────────────────

/**
 * The PRECEDENCE protocol state machine (`rohan-plan.md` §10 + `GAP.md` §1.2).
 *
 * Three tracks share one union:
 *  - PERFORMING: registration → race → proven settlement → draw → servicing → release → closed
 *  - DISTRESSED: the deterministic unwind, every step a permissionless keeper poke
 *  - utility:    AUTO_REFUND (outpaced capital returned) and ABORTED
 */
export const PROTOCOL_STATES = [
  // ── performing track ──
  "COLLATERAL_REGISTERED", // hash-unique NFT minted; clear title verified
  "RACE_OPEN", // financing window open on Sepolia PriorityVault
  "PRIORITY_SETTLED", // 0x0FD2 verified the locks; priority settled by (height, txIndex)
  "CAPITAL_DRAWN", // obligor drew capital from the vault
  "ENCUMBERED", // facility active; lien registered on Creditcoin
  "REFI_DISCOVERED", // Priority Agent proposed a rate improvement
  "ATOMIC_REFINANCE", // one block: old lien released + new lien created
  "REPAYMENT_PROOF", // repayment on Sepolia proven via Attestcoin
  "LIEN_RELEASED", // strict seniority waterfall paid; claims burned
  "SETTLED_CLOSED", // terminal: facility fully resolved, collateral clear

  // ── distressed track (permissionless, timestamp-gated) ──
  "FROZEN_DRAW", // overdraw attempt or title dispute; draws frozen
  "PCR_STABILIZATION", // coverage below threshold; top-up window open
  "GRACE_PERIOD", // repayment overdue; cure window before liquidation
  "DUTCH_LIQUIDATION", // descending-price auction of the collateral NFT
  "TERMINATED_DEFAULT", // terminal: loss allocated, obligor flagged DEFAULT
  "BREACHED", // collateral moved illegally; claims frozen, legal escalation

  // ── utility ──
  "AUTO_REFUND", // race produced locks but allocated nothing; capital returned
  "ABORTED", // terminal: race never became a facility
] as const;

export type LifecyclePhase = (typeof PROTOCOL_STATES)[number];

/** Back-compat alias — prefer PROTOCOL_STATES. */
export const LIFECYCLE_PHASES = PROTOCOL_STATES;

