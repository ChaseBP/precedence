/**
 * One Attestcoin verification of a priority race.
 *
 * Shaped to the real batch overload:
 *   verifyAndEmit(uint64 chainKey, uint64[] heights, bytes[] encodedTxs,
 *                 MerkleProof[] merkleProofs, ContinuityProof sharedContinuityProof)
 * A single continuity proof is shared across up to 10 transactions within a 1000-block window.
 */
export interface AttestcoinProofRecord {
  chainKey: number; // 1 = Sepolia
  /** One height per transaction — a race legitimately spans blocks. */
  heights: number[];
  /** Derived from each Merkle proof by calculateTxIndex, aligned with `heights`. */
  txIndices: number[];
  encodedTxs: Hex[];
  merkleProofs: MerkleProofData[];
  continuityProof: ContinuityProofData;
  batchSize: number;
  /** True once the free view-only `verify` passed off-chain, before spending gas. */
  preflightVerified: boolean;
  proofPipelineStatus: ProofPipelineStatus;
  /** Measured, not assumed. ~7–9 min sawtooth on Sepolia as of 2026-09-01. */
  attestationLagMinutes: number;
  /** Latest attested height reported by ChainInfo precompile 0x0FD3 when the proof was built. */
  attestedHeight?: number;
  proverAgent: AgentId;
  precompile: Hex;
  creditcoinTxHash?: Hex;
  verificationBlockNumber?: number;
  verifiedAt?: ISO;
  error?: string;
}

