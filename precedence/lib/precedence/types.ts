/**
 * PRECEDENCE protocol types — single source of truth for all shared types.
 *
 * The Proof-Ordered Capital Priority Protocol:
 *  - Ethereum Sepolia (chainKey 1) = source-chain capital locks (PriorityVault.sol, pUSD)
 *  - Creditcoin CC3 = Attestcoin Native Query Verifier precompile (0x0FD2), AttestationGate,
 *    PriorityEngine, CollateralRegistry, ClaimToken (ERC-1155), RefinanceEngine.
 *
 * Priority settles by proven `(blockHeight, txIndex)` ordering, where txIndex is derived on-chain
 * from the Merkle proof via `INativeQueryVerifier.calculateTxIndex`. A declared tranche is a
 * *preference*; proven ordering resolves contention within it.
 */

export type Hex = `0x${string}`;
export type AgentId = string; // "meridian" | "vector" | "novum" | "kestrel"
export type RaceId = string;
export type CollateralId = string;
export type ISO = string; // ISO-8601 timestamp

export type Tranche = "SENIOR" | "JUNIOR" | "SUBORDINATE";
export type TrancheNumber = 0 | 1 | 2; // 0=SENIOR, 1=JUNIOR, 2=SUBORDINATE

export type CollateralState =
  | "CLEAR"
  | "RACE_OPEN"
  | "PRIORITY_SETTLED"
  | "ENCUMBERED"
  | "FROZEN"
  | "GRACE"
  | "DUTCH_LIQUIDATION"
  | "REPAID"
  | "REFINANCED"
  | "DEFAULTED"
  | "BREACHED";

export type ProofPipelineStatus =
  | "PENDING_EVIDENCE" // source tx exists; attestation has not reached its height yet (a patient state)
  | "PROOF_AVAILABLE" // proof generated by the builder service
  | "VERIFIED" // precompile 0x0FD2 returned true on Creditcoin
  | "FAILED";

export type RiskTolerance = "conservative" | "balanced" | "aggressive";

